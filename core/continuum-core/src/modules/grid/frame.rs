//! Grid wire protocol types.
//!
//! GridFrame is the unit of communication between Continuum nodes.
//! It wraps Commands.execute() requests and Events.emit() payloads
//! with routing metadata, correlation IDs, and timestamps.
//!
//! Frame format on the wire: length-prefixed JSON (same as IPC protocol).
//! [4 bytes u32 BE length][JSON payload bytes]

use serde::{Deserialize, Serialize};
use serde_json::Value;

/// A single frame on the Grid wire protocol.
///
/// Every inter-node message — command request, command response,
/// event broadcast, or stream chunk — is wrapped in a GridFrame.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GridFrame {
    /// Frame type: request, response, event, or stream.
    #[serde(rename = "type")]
    pub frame_type: FrameType,

    /// Correlation ID — ties a request to its response(s).
    /// Generated by the sender, echoed by the responder.
    pub correlation_id: String,

    /// Source node identity (transport-specific address string).
    pub source_node: String,

    /// Target node identity (transport-specific address string).
    pub target_node: String,

    /// Timestamp in milliseconds since Unix epoch.
    pub timestamp: u64,

    /// The actual payload — command, result, event, or stream chunk.
    pub payload: GridPayload,
}

/// Frame type discriminant.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum FrameType {
    Request,
    Response,
    Event,
    Stream,
}

/// The payload within a GridFrame.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind")]
pub enum GridPayload {
    /// A Commands.execute() request being forwarded to a remote node.
    #[serde(rename = "command")]
    Command { command: String, params: Value },

    /// The result of a remote command execution.
    #[serde(rename = "command-result")]
    CommandResult {
        success: bool,
        #[serde(skip_serializing_if = "Option::is_none")]
        result: Option<Value>,
        #[serde(skip_serializing_if = "Option::is_none")]
        error: Option<String>,
    },

    /// An event being forwarded across the mesh.
    #[serde(rename = "event")]
    Event { event: String, data: Value },

    /// A chunk of a streaming response (large data transfer).
    #[serde(rename = "stream-chunk")]
    StreamChunk {
        data: Value,
        #[serde(rename = "final")]
        is_final: bool,
    },
}

impl GridFrame {
    /// Create a command request frame.
    pub fn command_request(
        correlation_id: String,
        source_node: String,
        target_node: String,
        command: String,
        params: Value,
    ) -> Self {
        Self {
            frame_type: FrameType::Request,
            correlation_id,
            source_node,
            target_node,
            timestamp: now_millis(),
            payload: GridPayload::Command { command, params },
        }
    }

    /// Create a success response frame (swaps source/target from the request).
    pub fn success_response(request: &GridFrame, result: Value) -> Self {
        Self {
            frame_type: FrameType::Response,
            correlation_id: request.correlation_id.clone(),
            source_node: request.target_node.clone(),
            target_node: request.source_node.clone(),
            timestamp: now_millis(),
            payload: GridPayload::CommandResult {
                success: true,
                result: Some(result),
                error: None,
            },
        }
    }

    /// Create an error response frame.
    pub fn error_response(request: &GridFrame, error: String) -> Self {
        Self {
            frame_type: FrameType::Response,
            correlation_id: request.correlation_id.clone(),
            source_node: request.target_node.clone(),
            target_node: request.source_node.clone(),
            timestamp: now_millis(),
            payload: GridPayload::CommandResult {
                success: false,
                result: None,
                error: Some(error),
            },
        }
    }

    /// Create an event frame (e.g., progress updates during long-running commands).
    pub fn event(
        correlation_id: String,
        source_node: String,
        target_node: String,
        event_name: String,
        data: Value,
    ) -> Self {
        Self {
            frame_type: FrameType::Event,
            correlation_id,
            source_node,
            target_node,
            timestamp: now_millis(),
            payload: GridPayload::Event {
                event: event_name,
                data,
            },
        }
    }

    /// Serialize this frame to length-prefixed bytes for wire transmission.
    /// Format: [4 bytes u32 BE length][JSON bytes]
    pub fn to_wire_bytes(&self) -> Result<Vec<u8>, String> {
        let json =
            serde_json::to_vec(self).map_err(|e| format!("Frame serialization failed: {e}"))?;
        let len = json.len() as u32;
        let mut buf = Vec::with_capacity(4 + json.len());
        buf.extend_from_slice(&len.to_be_bytes());
        buf.extend_from_slice(&json);
        Ok(buf)
    }

    /// Deserialize a frame from JSON bytes (without the length prefix).
    pub fn from_json_bytes(bytes: &[u8]) -> Result<Self, String> {
        serde_json::from_slice(bytes).map_err(|e| format!("Frame deserialization failed: {e}"))
    }
}

pub fn now_millis() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_frame_roundtrip() {
        let frame = GridFrame::command_request(
            "corr-001".into(),
            "node-a".into(),
            "node-b".into(),
            "gpu/stats".into(),
            serde_json::json!({}),
        );

        let bytes = frame.to_wire_bytes().unwrap();
        // First 4 bytes are length prefix
        let len = u32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]) as usize;
        assert_eq!(len, bytes.len() - 4);

        let decoded = GridFrame::from_json_bytes(&bytes[4..]).unwrap();
        assert_eq!(decoded.correlation_id, "corr-001");
        assert_eq!(decoded.frame_type, FrameType::Request);
        assert_eq!(decoded.source_node, "node-a");
        assert_eq!(decoded.target_node, "node-b");

        if let GridPayload::Command { command, .. } = &decoded.payload {
            assert_eq!(command, "gpu/stats");
        } else {
            panic!("Expected Command payload");
        }
    }

    #[test]
    fn test_response_swaps_source_target() {
        let request = GridFrame::command_request(
            "corr-002".into(),
            "laptop".into(),
            "home-5090".into(),
            "genome/train".into(),
            serde_json::json!({"epochs": 3}),
        );

        let response = GridFrame::success_response(&request, serde_json::json!({"loss": 0.031}));

        assert_eq!(response.source_node, "home-5090");
        assert_eq!(response.target_node, "laptop");
        assert_eq!(response.correlation_id, "corr-002");
    }

    #[test]
    fn test_payload_serde_tags() {
        let frame = GridFrame::event(
            "corr-003".into(),
            "a".into(),
            "b".into(),
            "genome:train:progress".into(),
            serde_json::json!({"epoch": 2, "loss": 0.043}),
        );

        let json = serde_json::to_value(&frame).unwrap();
        assert_eq!(json["payload"]["kind"], "event");
        assert_eq!(json["payload"]["event"], "genome:train:progress");
    }
}
