//! WorkspaceMapSource — grounds a persona in the SHAPE of its workspace: the
//! root it acts in plus the real top-level directory layout, packaged as a
//! `[workspace-map]` standing-framing block.
//!
//! ### Why this source exists (the glass-box finding)
//!
//! Asha's biggest cluster of coder-eval failures was searching
//! `file_glob: "src/**/*.rs"` — which matches ZERO files here, because this
//! repo's Rust lives under `core/continuum-core/src/` and root `src/` is the
//! legacy TS tree. The decisive question (Joel): *given her exact prompt, with
//! no a-priori knowledge of the layout, could you or I have done better?* No —
//! her standing prompt carried identity + grid context + the room roster, but
//! **no map of where code lives**. The layout only ever appeared reactively, as
//! an echoed error in recall after a failed glob. A capable reasoner makes the
//! same `src/**/*.rs` guess from that prompt. That is a GROUNDING hole, not
//! stupidity — the same class as not knowing who else is in the room.
//!
//! This source closes it: the workspace layout is true world-state the persona
//! reasons over, exactly like the roster (WHO is present) and the doctrine (WHAT
//! the room is for). This adds WHERE things live. It is grounding, never
//! steering: we surface the real top-level directories and the path semantics of
//! the tools; we do NOT script steps or name which directory holds the answer.
//!
//! ### Ground truth, no drift
//!
//! The map is generated by the SAME machinery the code tools resolve against —
//! a [`FileEngine`](crate::code::FileEngine) rooted at the process cwd, exactly as
//! `ensure_engine` (`modules::code_commands::ensure_engine`) builds the
//! persona's hands. So the directories named here are precisely the ones
//! `code/glob` / `code/list` will see; the map cannot describe a layout the tools
//! don't share. When airc-owned per-persona workspace isolation lands (#49), the
//! reader swaps to the leased root and every persona — including remote grid
//! peers with no local filesystem intuition — shares ONE consistent view.
//!
//! ### Doctrine alignment
//!
//! - [[substrate-is-a-good-citizen-on-the-host]]: a failed layout read returns
//!   an empty delivery — cognition stays up; no block rather than a panic.
//! - Persona-scoped at construction (defense in depth, same as roster/doctrine).
//! - [[solve-for-public-users]]: the map is the ACTUAL layout of whatever repo
//!   the core runs in — zero repo-specific prose, true for any checkout.
//! - [[no-hardcoded-heuristics-to-steer-cognition]]: we ground her in facts, we
//!   never tell her which directory to look in or what step to take next.

